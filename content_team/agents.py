def get_all_agents() -> dict[str, AgentDefinition]:
    """全エージェントの定義を返す"""
    return {
        "researcher": create_researcher_agent(),
        "scientist": create_scientist_agent(),
        "writer": create_writer_agent(),
        "fact_checker": create_fact_checker_agent(),
        "ux_planner": create_ux_planner_agent(),
    }
